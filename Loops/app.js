//for loop
for(let i=0;i<5;i++){
    console.log("Hi");
}

//while

let i=5;
while(i<=20){
    console.log(i);
    i++;
}

//do while

let k=1;
do{
console.log(k);
k++;
}while(k<=5);

//break

for(let i=0;i<=8;i++){
    if(i==7){
        break;
    }
    console.log(i);
}


//continue

for(let i=2;i<=4;i++){
    if(i==3){
        continue;
    }
    console.log(i);
}

